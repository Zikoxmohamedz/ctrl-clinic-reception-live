import assert from 'node:assert/strict';
import {calculateAccounts} from '../pages/accounting-engine.mjs';
import {buildInsights} from '../pages/inventory-insights.mjs';
const materials=[{id:'a',name:'A',code:'A',unit:'ml',cost_price:5},{id:'b',name:'B',code:'B',unit:'piece',cost_price:0}];
